const FAQ_LD = {
  "@context": "https://schema.org",
  "@type": "FAQPage",
  inLanguage: "ar",
  mainEntity: FAQS.map(([q, a]) => ({
    "@type": "Question",
    name: q,
    acceptedAnswer: { "@type": "Answer", text: a },
  })),
};

/* العناوين التي تظهر في الإجابات، تُعرض روابط. النص الظاهر لا يُمس،
   فيبقى مطابقًا للمخطط كلمةً كلمة. الأطول أولًا كي لا يلتقط hysaab.ai/ar
   بداية المسارات الأعمق. */
const LINKS: Record<string, string> = {
  "hysaab.ai/ar/contact": "/ar/contact",
  "hysaab.ai/ar/pricing": "/ar/pricing",
  "hysaab.ai/ar": "/ar",
  "info@hysaab.ai": "mailto:info@hysaab.ai",
};
const LINK_RE = /(hysaab\.ai\/ar\/contact|hysaab\.ai\/ar\/pricing|hysaab\.ai\/ar|info@hysaab\.ai)/g;

function linkify(text: string): React.ReactNode[] {
  return text.split(LINK_RE).map((part, i) =>
    LINKS[part] ? <a key={i} href={LINKS[part]} dir="ltr">{part}</a> : part,
  );
}

