// Writes lib/expansions.index.ts: one static import per JSON file in
// content/expansions/{guides,tools}, so Next bundles them at build time.
import { readdirSync, writeFileSync } from "node:fs";
const kinds = ["guides", "tools"];
let out = "/* Generated by scripts/index-expansions.mjs. Do not edit by hand. */\n";
const maps = {};
for (const k of kinds) {
  const files = readdirSync(`content/expansions/${k}`).filter((f) => f.endsWith(".json")).sort();
  maps[k] = files.map((f, i) => {
    const id = `${k[0]}${i}`;
    out += `import ${id} from "@/content/expansions/${k}/${f}";\n`;
    return `  ${JSON.stringify(f.replace(/\.json$/, ""))}: ${id} as any,`;
  });
}
out += `\nexport const GUIDE_FILES: Record<string, any> = {\n${maps.guides.join("\n")}\n};\n`;
out += `export const TOOL_FILES: Record<string, any> = {\n${maps.tools.join("\n")}\n};\n`;
writeFileSync("lib/expansions.index.ts", out);
console.log(`indexed ${maps.guides.length} guides, ${maps.tools.length} tools`);
